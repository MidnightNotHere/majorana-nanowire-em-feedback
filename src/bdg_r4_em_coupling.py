# FUNCTION 5 — Mutual inductance between circuit loop and nanowire
# ════════════════════════════════════════════════════════════════════
def compute_mutual_inductance(N: int,
                              lattice_const: float,
                              loop_height: float,
                              loop_width: float,
                              n_loop_seg: int = 200,
                              ) -> float:
    """
    Mutual inductance M (Henries) between the nanowire and a rectangular
    circuit loop, via the discretised Neumann double integral

        M = (mu_0 / 4pi) * sum_i sum_j (dl_wire_i . dl_loop_j)
                                       / |r_wire_i - r_loop_j|.

    Geometry / modelling note
    -------------------------
    Neumann's formula only gives a non-zero contribution between segments
    that are PARALLEL.  A loop lying purely in the y-z plane (perpendicular
    to an x-directed wire) has NO segment parallel to the wire and a
    symmetric threading gives M = 0 by cancellation -- the genuine
    inductive coupling that shifts the phase boundary is the self-field
    feedback handled in R5.  For the circuit-level observable we therefore
    model the standard wire / rectangular-loop configuration: the loop's
    two long sides run parallel to the wire (along x) with length
    `loop_width`, the near side at transverse distance loop_height/2 and
    the far side at loop_height/2 + loop_height (the two perpendicular
    return segments contribute zero).  This reproduces the textbook
    closed form  M = (mu_0 * loop_width / 2pi) * ln(d_far / d_near).

    Parameters
    ----------
    N             : number of wire sites (wire length = N * lattice_const)
    lattice_const : a, lattice constant in metres
    loop_height   : transverse dimension L_z of the loop (metres)
    loop_width    : length of the loop sides parallel to the wire (metres)
    n_loop_seg    : discretisation of each parallel loop side

    Returns
    -------
    M : mutual inductance in Henries.
    """
    a = lattice_const
    L_wire = N * a

    # wire segments along x, centred on x = 0
    x_w = (np.arange(N) + 0.5) * a - L_wire / 2.0               # (N,)  m
    dl_w = a                                                    # m

    # loop's two long sides along x, length loop_width, centred on x = 0
    dl_l = loop_width / n_loop_seg                              # m
    x_l = (np.arange(n_loop_seg) + 0.5) * dl_l - loop_width / 2.0  # (M,)

    d_near = loop_height / 2.0                                  # m
    d_far  = d_near + loop_height                              # m

    dx = x_w[:, None] - x_l[None, :]                           # (N, M) m
    r_near = np.sqrt(dx**2 + d_near**2)                        # (N, M) m
    r_far  = np.sqrt(dx**2 + d_far**2)                         # (N, M) m

    # near side current parallel to wire (+), far side antiparallel (-)
    integ = (dl_w * dl_l) * (1.0 / r_near - 1.0 / r_far)       # m
    M = (MU_0 / (4.0 * np.pi)) * np.sum(integ)                 # H
    return float(M)


# ════════════════════════════════════════════════════════════════════
# FUNCTION 6 — Reactive circuit impedance (experimental observable)
# ════════════════════════════════════════════════════════════════════
def compute_reactive_impedance(omega: float,
                               L: float,
                               M: float,
                               Z_wire: complex,
                               ) -> complex:
    """
    Reactive impedance of the circuit seen by an experimentalist:

        Z_r(omega) = i omega L  -  i omega^2 M^2 / Z_wire

    Parameters
    ----------
    omega  : angular frequency (rad/s)
    L      : effective circuit self-inductance (H)  -- tuned in R5
    M      : mutual inductance loop<->wire (H), from compute_mutual_inductance
    Z_wire : wire impedance at omega (Ohm, complex)

    Returns
    -------
    Z_r : complex impedance (Ohm).
    """
    return 1j * omega * L - 1j * omega**2 * M**2 / Z_wire       # Ohm


