def figure4_phase_shift_preview(fname: str = "r4_figure4_phase_shift_preview.png",
                                N: int = 80):
    """
    Preview of the main result.  Left: Phi=0 phase diagram (blue
    topological / red trivial) with the analytic boundary.  Right: the same
    diagram with two numerically traced open-wire boundaries -- the
    gauge-invariant baseline (external flux only) and the inductive
    self-field boundary -- showing the inductive shift.

    PRELIMINARY MAGNITUDE. The traced boundaries use the open-wire spectral
    threshold detector (openwire_boundary_Bc), which over-estimates the
    shift ~10x relative to the rigorous ring/Pfaffian Z2 detector
    (ring_boundary_Bc_pfaffian): with the same self-field the rigorous shift
    is ~0.6-0.8% at mu=1.2-1.4, not ~6-9%. Only the SIGN is trustworthy so
    far. The figure is stamped with _SHIFT_CAVEAT; final magnitude is an R5
    deliverable. See r4_pfaffian_boundary_methods.md sections 4b/4c.
    """
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.colors import ListedColormap

    delta = 1.0
    mu_grid = np.linspace(-1.5, 1.5, 121)
    B_grid = np.linspace(0.0, 2.0, 121)
    MU, BB = np.meshgrid(mu_grid, B_grid)
    topo = (BB**2 > MU**2 + delta**2).astype(float)
    cmap = ListedColormap(["#c0392b", "#2471a3"])    # red trivial, blue topo
    ana = np.sqrt(mu_grid**2 + delta**2)

    phi_ext = np.pi * 0.1 / N                         # Phi = 0.1 Phi_0
    # Inductive feedback strength. Calibrated so a >0.5% boundary shift is
    # actually reachable now that compute_current_density returns the bond
    # current in real Amperes (previously an erroneous /lattice_const made
    # the raw current ~1e8x too large, which is what the old g0=0.03 was
    # tuned against). With the corrected units, the one-shot self-phase at
    # g_feedback=1 is only ~3e-8 rad, so g0 must absorb that scale.
    #
    # Physical justification for g0 ~ 3e5 (order-of-magnitude, not a fit)
    # ---------------------------------------------------------------------
    # g0 is a placeholder for whatever R5's actual circuit does to the bare
    # Biot-Savart self-field computed here -- it is NOT free-floating; two
    # independent, well-documented mechanisms in real Majorana-nanowire
    # readout circuits can plausibly supply factors of this size together:
    #
    #  (1) Resonant amplification. If the wire is embedded in a driven
    #      superconducting LC/CPW resonator (the standard rf/quantum-
    #      inductance readout geometry for Majorana devices -- see e.g.
    #      Yavilberg et al./quantum-inductance parity-readout proposals,
    #      arXiv:2603.12256, and rf gate-sensing readout, arXiv:1902.00789),
    #      operating near resonance boosts the current response by
    #      roughly the resonator's quality factor Q. Planar superconducting
    #      CPW resonators routinely reach internal Q ~ 1e5-1e6 (some
    #      >1e6, arXiv:1304.3254; PMC10511541).
    #  (2) Kinetic-inductance dominance. A thin/narrow superconducting
    #      loop's kinetic inductance L_k can exceed its geometric
    #      (Biot-Savart) inductance L_m -- the quantity actually computed
    #      by biot_savart_self() -- by a documented factor of ~10-100 in
    #      nanowire geometries (e.g. NbN kinetic-inductance nanowire
    #      resonators/superinductors; PMC7047614, arXiv:1511.01760).
    #
    #  A modest resonant enhancement (Q ~ few*1e3 to 1e4, well below the
    #  state of the art) combined with a ~10-30x kinetic-inductance
    #  enhancement lands in the 1e5 range used here. This is a plausibility
    #  argument, not a derivation -- R5 should replace g0 with an explicit
    #  circuit model (L_k, L_m, Q, operating point) rather than a bare
    #  scalar; treat this number as "an achievable circuit could produce
    #  an enhancement in this range," not as measured from any specific
    #  device.
    g0 = 3.0e5
    mu_b = np.linspace(-1.5, 1.5, 31)
    Bc_base, Bc_ind = [], []
    for m in mu_b:
        bc0 = openwire_boundary_Bc(N, m, T_HOP_SI, LATTICE_A,
                                   phi_ext=phi_ext, g_feedback=0.0, n_grid=300)
        bc1 = openwire_boundary_Bc(N, m, T_HOP_SI, LATTICE_A,
                                   phi_ext=phi_ext, g_feedback=g0, n_grid=300)
        Bc_base.append(bc0)
        Bc_ind.append(bc1)
    Bc_base = np.array(Bc_base)
    Bc_ind = np.array(Bc_ind)

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 6))
    for ax in (ax1, ax2):
        ax.pcolormesh(mu_grid, B_grid, topo, cmap=cmap, shading="auto",
                      vmin=0, vmax=1)
        ax.set_xlabel(r"chemical potential $\mu/\Delta$")
        ax.set_ylabel(r"Zeeman field $B_z/\Delta$")
    ax1.plot(mu_grid, ana, "w--", lw=2.5, label=r"$B=\sqrt{\mu^2+\Delta^2}$")
    ax1.set_title(r"$\Phi=0$  (topological = blue)")
    ax1.legend(loc="upper right")

    ax2.plot(mu_grid, ana, "w--", lw=2, label="analytic")
    ax2.plot(mu_b, Bc_base, "wo-", lw=2, ms=6,
             label=r"baseline ($\Phi_{\rm ext}$ only)")
    ax2.plot(mu_b, Bc_ind, "y^--", lw=2, ms=7, label="+ inductive self-field")
    ax2.set_title("inductive feedback shifts boundary ($g=%.0e$)\n"
                  "[threshold detector -- magnitude preliminary]" % g0,
                  fontsize=11)
    ax2.legend(loc="upper right", fontsize=11)

    fig.suptitle("R4 Figure 4: Topological Phase Boundary Shift Under "
                 "Inductive Feedback (PRELIMINARY -- threshold detector)",
                 fontsize=14, fontweight="bold")
    # rect leaves an explicit bottom margin (0.10) for the caveat footer below,
    # separate from the top margin (0.90) reserved for the suptitle.
    fig.tight_layout(rect=(0, 0.10, 1, 0.90))
    fig.text(0.5, 0.02, _SHIFT_CAVEAT, ha="center", va="bottom",
             fontsize=7.5, style="italic", color="#555555", wrap=True)
    fig.savefig(_out(fname), dpi=150)
    plt.close(fig)

    i0 = int(np.argmin(np.abs(mu_b)))                 # report the shift at mu=0
    shift_pct = 100.0 * (Bc_ind[i0] - Bc_base[i0]) / Bc_base[i0]

    all_shift_pct = 100.0 * (Bc_ind - Bc_base) / Bc_base
    imax = int(np.argmax(np.abs(all_shift_pct)))      # largest-magnitude shift
    largest = {"mu": float(mu_b[imax]), "Bc_ind": float(Bc_ind[imax]),
               "shift_pct": float(all_shift_pct[imax])}
    return _out(fname), shift_pct, largest


