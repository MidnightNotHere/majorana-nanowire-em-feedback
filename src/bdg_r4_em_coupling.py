# PHYSICAL CONSTANTS (SI) — used only at the Biot-Savart / circuit layer
# ════════════════════════════════════════════════════════════════════
PHI_0    = 2.0678e-15        # Wb,   superconducting flux quantum h/2e
MU_0     = 4.0 * np.pi * 1e-7  # H/m, vacuum permeability
HBAR     = 1.0546e-34        # J*s,  reduced Planck constant
E_CHARGE = 1.6022e-19        # C,    elementary charge

# ── InAs/Al device parameters (Mourik et al., Science 336, 1003 (2012);
#    Lutchyn, Sau & Das Sarma, PRL 105, 077001 (2010)) ────────────────
M_STAR    = 0.023 * 9.109e-31     # kg,   effective mass (0.023 m_e)
G_FACTOR  = 10.0                  # dimensionless, InAs g-factor
DELTA_0   = 0.25e-3 * E_CHARGE    # J,    induced gap ~250 ueV
ALPHA_SO  = 20e-3 * E_CHARGE * 1e-9  # J*m, Rashba coefficient 20 meV*nm
LATTICE_A = 10e-9                 # m,    tight-binding lattice constant (10 nm)
WIRE_L    = 1e-6                  # m,    wire length 1 um  -> N = 100 sites
WIRE_R    = 50e-9                 # m,    wire radius 50 nm

# Derived tight-binding hopping in SI (Joules): t = hbar^2 / (2 m* a^2)
T_HOP_SI  = HBAR**2 / (2.0 * M_STAR * LATTICE_A**2)   # J


# ════════════════════════════════════════════════════════════════════
# Internal helper — site / sector index maps for the kron(spin, site)
# ordering.  Cached per N because R5 calls the EM layer hundreds of times.
# ════════════════════════════════════════════════════════════════════
_INDEX_CACHE: dict[int, tuple[np.ndarray, np.ndarray]] = {}


def _site_sector_maps(N: int) -> tuple[np.ndarray, np.ndarray]:
    """
    Return (site, is_elec) integer/boolean arrays of length 4N for the
    kron(spin, site) Nambu ordering.

      site[p]    = lattice site index of full-basis index p  (0..N-1)
      is_elec[p] = True if p is an electron component (p < 2N)

    Used by apply_peierls_phases to locate nearest-neighbour bonds.
    """
    if N not in _INDEX_CACHE:
        idx     = np.arange(4 * N)
        is_elec = idx < 2 * N
        site    = np.where(is_elec, idx % N, (idx - 2 * N) % N)
        _INDEX_CACHE[N] = (site, is_elec)
    return _INDEX_CACHE[N]


