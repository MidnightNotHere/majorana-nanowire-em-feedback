# FUNCTION 3 — Quasi-static Biot-Savart self vector potential
# ════════════════════════════════════════════════════════════════════
def biot_savart_self(j_x: np.ndarray,
                     N: int,
                     lattice_const: float,
                     wire_radius: float | None = None,
                     ) -> np.ndarray:
    """
    Self-induced x-component of the vector potential at every bond
    midpoint, from the wire current via a discrete Biot-Savart kernel.

    Physics (magnetostatic / quasi-static limit)
    --------------------------------------------
    Off-diagonal (i != j):
        A_self(x_i) += (mu_0 / 4pi) * j_x(j) * a / |x_i - x_j|
    Self term (i == j), finite-segment analytic regularisation:
        A_self(x_i) += (mu_0 / 4pi) * j_x(i) * 2 * ln(a / r_wire)

    The logarithmic self-term is the standard finite-segment kernel; the
    wire radius r_wire regularises the line-current divergence (do NOT set
    r_wire = 0 or r_wire = a, which give a singular / zero self-term).

    Fully vectorised (kernel matrix @ j_x); no Python loop over N, because
    R5's self-consistent loop calls this hundreds of times.

    Parameters
    ----------
    j_x           : (N-1,) current density at bond midpoints (A/m^2)
    N             : number of lattice sites
    lattice_const : a, lattice constant in metres
    wire_radius   : r_wire in metres for the self-term (default a/10)

    Returns
    -------
    A_self : (N-1,) vector potential at each bond midpoint, SI (T*m).

    Edge cases: N=1 -> empty array; N=2 -> single self-term only.

    Validation
    ----------
    Checked by Validation 2 (uniform current vs finite-segment analytic
    result, relative error < 1%).
    """
    j_x = np.asarray(j_x, dtype=float)
    n_bond = N - 1
    if n_bond <= 0:
        return np.zeros(0, dtype=float)

    a = lattice_const
    r_wire = a / 10.0 if wire_radius is None else wire_radius   # m

    # bond-midpoint positions  x_mid(i) = (i + 0.5) a  (metres)
    x_mid = (np.arange(n_bond) + 0.5) * a                       # (N-1,)

    # kernel[i, j] = a / |x_i - x_j|  (i != j),  2 ln(a/r_wire)  (i == j)
    diff = x_mid[:, None] - x_mid[None, :]                      # (N-1, N-1) m
    absd = np.abs(diff)
    kernel = np.zeros_like(diff)
    off = ~np.eye(n_bond, dtype=bool)
    kernel[off] = a / absd[off]                                 # dimensionless * m? see below
    np.fill_diagonal(kernel, 2.0 * np.log(a / r_wire))          # dimensionless

    A_self = (MU_0 / (4.0 * np.pi)) * (kernel @ j_x)            # T*m
    return A_self


# ════════════════════════════════════════════════════════════════════
# FUNCTION 4 — Peierls phase from a vector potential
# ════════════════════════════════════════════════════════════════════
def compute_peierls_from_A(A_self: np.ndarray,
                           lattice_const: float,
                           ) -> np.ndarray:
    """
    Convert a per-bond vector potential into dimensionless Peierls phases.

        phi_self(i) = (e / hbar) * A_self(i) * a

    Parameters
    ----------
    A_self        : (N-1,) vector potential at bond midpoints (T*m)
    lattice_const : a, lattice constant in metres

    Returns
    -------
    phi_self : (N-1,) dimensionless Peierls phases.

    Validation
    ----------
    Checked by Validation 1 (uniform A field gives uniform phase equal to
    (e/hbar) * A_0 * a).
    """
    A_self = np.asarray(A_self, dtype=float)
    return (E_CHARGE / HBAR) * A_self * lattice_const          # dimensionless


