def _run_validations() -> bool:
    from scipy.linalg import eigh
    a = LATTICE_A
    results: list[tuple[str, bool, str]] = []

    # [1/6] uniform A -> uniform Peierls phases
    N = 100
    A0 = 1.0e-9
    phi = compute_peierls_from_A(np.full(N - 1, A0), a)
    err1 = float(np.max(np.abs(phi - phi[0])))
    ok1 = (np.allclose(phi, phi[0], rtol=1e-12)
           and abs(phi[0] - (E_CHARGE / HBAR) * A0 * a) < 1e-10)
    results.append(("Uniform A -> Peierls phases", ok1,
                    f"error < {max(err1, 1e-16):.0e}"))

    # [2/6] Biot-Savart analytic comparison
    j0, r_wire = 1.0, a / 10.0
    A_self = biot_savart_self(np.full(N - 1, j0), N, a, r_wire)
    L = N * a
    A_an = (MU_0 / (4 * np.pi)) * j0 * (2 * np.log(L / (2 * r_wire)) + 2 * _EULER_GAMMA)
    rel2 = abs(A_self[N // 2] - A_an) / abs(A_an)
    results.append(("Biot-Savart analytic comparison", rel2 < 0.01,
                    f"rel error = {rel2*100:.2f}%  [target < 1%]"))

    # [3/6] PH symmetry after phases (10 phases x 3 sizes)
    rng = np.random.default_rng(2027)
    max_eps = 0.0
    for Nn in (20, 50, 100):
        Hn = build_bdg_lo(Nn, mu=rng.uniform(-2, 2), B_zeeman=rng.uniform(0, 1.5))
        for _ in range(10):
            Hm = apply_peierls_phases(Hn, Nn, rng.uniform(0, np.pi),
                                      rng.uniform(-0.5, 0.5, Nn - 1))
            max_eps = max(max_eps, check_ph_symmetry_complex(Hm, Nn))
    results.append(("PH symmetry after phases", max_eps < 1e-10,
                    f"eps_PH = {max_eps:.2e}"))

    # [4/6] zero flux -> H unchanged
    H = build_bdg_lo(N, mu=0.5, B_zeeman=0.7)
    maxdiff = float(np.max(np.abs(H - apply_peierls_phases(H, N, 0.0, None))))
    results.append(("Zero flux -> H unchanged", maxdiff < 1e-14,
                    f"max diff = {maxdiff:.2e}"))

    # [5/6] current density units/sign: zero at TRIM, reverses under phi->-phi
    w, v = eigh(build_bdg_lo(60, mu=0.0, B_zeeman=0.0))
    j_trim = compute_current_density(v, w, 60, T_HOP_SI, np.zeros(59), a)
    trim_zero = (abs(float(np.sum(j_trim))) < 1e-6
                 and float(np.max(np.abs(j_trim))) < 1e-6)
    w, v = eigh(build_bdg_lo(60, mu=0.0, B_zeeman=1.5))
    phi_b = np.full(59, 0.3)
    jp = compute_current_density(v, w, 60, T_HOP_SI, phi_b, a)
    jm = compute_current_density(v, w, 60, T_HOP_SI, -phi_b, a)
    reverses = np.allclose(jp, -jm, rtol=1e-8, atol=1e-30)
    results.append(("Current density units/sign", trim_zero and reverses,
                    "TRIM current=0, reverses under phi->-phi"))

    # [6/6] phase boundary: uniform flux is gauge-invariant (ring shift ~0);
    #        inductive self-field shifts the boundary (correctly directed)
    Nr = 100
    Bc0_ring = ring_boundary_Bc(Nr, 0.0, 0.0)
    BcF_ring = ring_boundary_Bc(Nr, 0.0, np.pi * 0.1 / Nr)
    gauge_shift = 100.0 * (BcF_ring - Bc0_ring) / Bc0_ring
    Nw = 80
    phi_w = np.pi * 0.1 / Nw
    Bc_base = openwire_boundary_Bc(Nw, 0.0, T_HOP_SI, LATTICE_A, phi_w, 0.0)
    Bc_ind = openwire_boundary_Bc(Nw, 0.0, T_HOP_SI, LATTICE_A, phi_w, 0.03)
    ind_shift = 100.0 * (Bc_ind - Bc_base) / Bc_base
    ok6 = abs(gauge_shift) < 1.0 and abs(ind_shift) > 0.5
    results.append(("Phase diagram shift under flux", ok6,
                    f"uniform(gauge)={gauge_shift:+.2f}% ~0, "
                    f"inductive={ind_shift:+.1f}% at mu=0"))

    print("\n" + "=" * 60)
    print("R4 VALIDATION SUMMARY")
    print("=" * 60)
    all_pass = True
    for i, (name, ok, detail) in enumerate(results, 1):
        all_pass = all_pass and ok
        print(f"[{i}/6] {name:<33s} {'PASS' if ok else 'FAIL'}  ({detail})")
    print("=" * 60)
    if all_pass:
        print("R4 complete. PeierlsEMLayer ready for R5 self-consistent loop.")
        print("Import: from bdg_r4_em_coupling import PeierlsEMLayer")
    else:
        print("R4 INCOMPLETE -- one or more validations failed.")
    print("=" * 60)
    return all_pass


