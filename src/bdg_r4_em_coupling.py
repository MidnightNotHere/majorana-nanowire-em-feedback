# FUNCTION 1 — Peierls phase substitution on the BdG Hamiltonian
# ════════════════════════════════════════════════════════════════════
def apply_peierls_phases(H_BdG: np.ndarray,
                         N: int,
                         phi_ext: float,
                         phi_self: np.ndarray | None = None,
                         ) -> np.ndarray:
    """
    Apply Peierls phase substitution to a 4N x 4N Lutchyn-Oreg BdG
    Hamiltonian for a uniform external-flux phase plus an optional
    per-bond self-induced phase.

    Physics
    -------
    The Peierls substitution multiplies every nearest-neighbour hopping
    amplitude (kinetic AND Rashba spin-orbit) that transfers charge from
    site i to site i+1 by a complex phase:

        t_{i,i+1} -> t_{i,i+1} * exp(+i * phi_i)        (electron block)
        t_{i,i+1} -> t_{i,i+1} * exp(-i * phi_i)        (hole block)

    with  phi_i = phi_ext + phi_self[i].  The hole (lower-right 2N x 2N)
    block picks up the conjugate phase (tau_z structure), which is exactly
    what preserves particle-hole symmetry.  On-site terms (chemical
    potential, Zeeman) and the s-wave pairing block (which is on-site)
    are left untouched.

    Implementation builds a real antisymmetric phase matrix theta with
    theta[p, q] = -theta[q, p], so that H * exp(i*theta) is Hermitian by
    construction.  For a forward electron bond (site q = site p + 1, same
    Nambu sector) theta = +phi_i; for the hole sector theta = -phi_i.
    Because the kron(spin, site) ordering puts the Rashba cross-spin
    hopping at (site i -> site i+1) too, this single rule captures every
    bond automatically (verified by the PH-symmetry assertion).

    Parameters
    ----------
    H_BdG    : (4N, 4N) complex ndarray, Lutchyn-Oreg BdG Hamiltonian
    N        : number of lattice sites
    phi_ext  : uniform external-flux phase per bond (dimensionless)
               = pi * Phi_ext / Phi_0 / N
    phi_self : (N-1,) per-bond self-induced phase (dimensionless) or None

    Returns
    -------
    H_mod : (4N, 4N) complex ndarray with Peierls phases applied.

    Raises
    ------
    ValueError if particle-hole symmetry is broken (eps_PH > 1e-10) after
    the substitution.

    Validation
    ----------
    Checked by Validation 1 (uniform phase), Validation 3 (PH symmetry
    preserved for random phases & sizes) and Validation 4 (zero flux ->
    identity).
    """
    if H_BdG.shape != (4 * N, 4 * N):
        raise ValueError(
            f"H_BdG has shape {H_BdG.shape}, expected {(4*N, 4*N)} for N={N}."
        )

    # ── Per-bond total phase (dimensionless), length N-1 ──────────────
    phi_bond = np.full(N - 1, float(phi_ext))            # external flux
    if phi_self is not None:
        phi_self = np.asarray(phi_self, dtype=float)
        if phi_self.shape != (N - 1,):
            raise ValueError(
                f"phi_self has shape {phi_self.shape}, expected {(N-1,)}."
            )
        phi_bond = phi_bond + phi_self                   # add self term

    # ── Fast path: no phase at all -> return unchanged copy ───────────
    if not np.any(phi_bond):
        return H_BdG.copy()

    site, is_elec = _site_sector_maps(N)

    # forward bonds: same Nambu sector, site(q) == site(p) + 1
    same_sector = is_elec[:, None] == is_elec[None, :]      # (4N, 4N)
    forward     = same_sector & (site[None, :] == site[:, None] + 1)

    theta = np.zeros((4 * N, 4 * N), dtype=float)
    rows, cols = np.where(forward)
    bond_idx   = site[rows]                                  # = site(p) in 0..N-2
    sector_sgn = np.where(is_elec[rows], 1.0, -1.0)          # +1 elec, -1 hole
    theta[rows, cols] = sector_sgn * phi_bond[bond_idx]
    theta = theta - theta.T                                  # antisymmetrise

    H_mod = H_BdG * np.exp(1j * theta)                       # Hermitian-preserving

    # ── Never silently proceed with a symmetry-broken Hamiltonian ─────
    eps_ph = check_ph_symmetry_complex(H_mod, N)            # raises if > 1e-10
    if eps_ph > 1e-10:                                       # belt and braces
        raise ValueError(
            f"Peierls substitution broke PH symmetry: eps_PH = {eps_ph:.2e}."
        )
    return H_mod


# ════════════════════════════════════════════════════════════════════
# FUNCTION 2 — Current density from the BdG ground state
# ════════════════════════════════════════════════════════════════════
def compute_current_density(eigenvectors: np.ndarray,
                            eigenvalues: np.ndarray,
                            N: int,
                            t_hop: float,
                            phi_total: np.ndarray,
                            lattice_const: float,
                            ) -> np.ndarray:
    """
    Compute the x-directed current density at each bond midpoint from the
    BdG ground state (all negative-energy states filled).

    Physics
    -------
    The tight-binding bond current between sites i and i+1 is

        j_x(i) = (2 e t_hop / hbar / a)
                 * sum_{n : E_n < 0} Im[ u_n^dagger(i)
                                         * exp(i phi_total(i))
                                         * u_n(i+1) ]

    where u_n(i) is the 2-component electron spinor (spin up, spin down)
    at site i of BdG eigenvector n, and the spin inner product is
        u_n^d(i) . u_n(i+1) = conj(u_up_i) u_up_{i+1}
                              + conj(u_dn_i) u_dn_{i+1}.
    The factor 2 comes from BdG doubling (particle + hole).  Only the
    electron components (first 2N entries) enter — including the hole
    components would double-count.

    BdG occupation convention: "occupied" == E_n < 0 (the BdG ground
    state).  Positive-energy states are the PH partners and are NOT
    counted.

    Parameters
    ----------
    eigenvectors  : (4N, 4N) BdG eigenvectors (columns), as returned by eigh
    eigenvalues   : (4N,) BdG eigenvalues
    N             : number of lattice sites
    t_hop         : hopping amplitude in physical units (Joules) — sets the
                    SI scale of the returned current density
    phi_total     : (N-1,) total Peierls phase per bond (dimensionless)
    lattice_const : a, lattice constant in metres

    Returns
    -------
    j_x : (N-1,) current density at each bond midpoint, SI units (A/m^2).

    Note on units: with t_hop in Joules, e*t/hbar/a has units
    C*J/(J*s*m) = A/m.  The returned array follows the project convention
    of labelling this the current density driving the Biot-Savart kernel;
    biot_savart_self() folds in the remaining lattice factor.  The
    validations exercise sign and (near-)zero behaviour, which are
    convention-independent.

    Validation
    ----------
    Checked by Validation 5 (units/sign: vanishes at the time-reversal
    invariant point mu=B=0, reverses under phi -> -phi).
    """
    eigenvalues = np.asarray(eigenvalues)
    occ = eigenvalues < 0.0                                  # BdG ground state

    # electron block = first 2N rows; columns = occupied eigenvectors
    U = eigenvectors[:2 * N, occ]                            # (2N, n_occ) complex
    if U.shape[1] == 0:
        return np.zeros(N - 1, dtype=float)

    # reshape to (spin=2, site=N, n_occ) for the kron(spin, site) ordering
    U = U.reshape(2, N, -1)                                  # row 0 = up, row 1 = dn
    u_i   = U[:, :-1, :]                                     # (2, N-1, n_occ)
    u_ip1 = U[:,  1:, :]                                     # (2, N-1, n_occ)

    # spin inner product  sum_s conj(u_s(i)) u_s(i+1)  -> (N-1, n_occ)
    inner = np.sum(np.conj(u_i) * u_ip1, axis=0)

    phase = np.exp(1j * np.asarray(phi_total, dtype=float))[:, None]  # (N-1,1)

    prefactor = 2.0 * E_CHARGE * t_hop / HBAR / lattice_const  # A/m  (see docstring)
    j_x = prefactor * np.sum(np.imag(inner * phase), axis=1)   # (N-1,)
    return j_x


# ════════════════════════════════════════════════════════════════════
# FUNCTION 3 — Quasi-static Biot-Savart self vector potential
# ════════════════════════════════════════════════════════════════════
def biot_savart_self(j_x: np.ndarray,
                     N: int,
                     lattice_const: float,
                     wire_radius: float | None = None,
                     ) -> np.ndarray:
    """
    Self-induced x-component of the vector potential at every bond
    midpoint, from the wire current via a discrete Biot-Savart kernel.

    Physics (magnetostatic / quasi-static limit)
    --------------------------------------------
    Off-diagonal (i != j):
        A_self(x_i) += (mu_0 / 4pi) * j_x(j) * a / |x_i - x_j|
    Self term (i == j), finite-segment analytic regularisation:
        A_self(x_i) += (mu_0 / 4pi) * j_x(i) * 2 * ln(a / r_wire)

    The logarithmic self-term is the standard finite-segment kernel; the
    wire radius r_wire regularises the line-current divergence (do NOT set
    r_wire = 0 or r_wire = a, which give a singular / zero self-term).

    Fully vectorised (kernel matrix @ j_x); no Python loop over N, because
    R5's self-consistent loop calls this hundreds of times.

    Parameters
    ----------
    j_x           : (N-1,) current density at bond midpoints (A/m^2)
    N             : number of lattice sites
    lattice_const : a, lattice constant in metres
    wire_radius   : r_wire in metres for the self-term (default a/10)

    Returns
    -------
    A_self : (N-1,) vector potential at each bond midpoint, SI (T*m).

    Edge cases: N=1 -> empty array; N=2 -> single self-term only.

    Validation
    ----------
    Checked by Validation 2 (uniform current vs finite-segment analytic
    result, relative error < 1%).
    """
    j_x = np.asarray(j_x, dtype=float)
    n_bond = N - 1
    if n_bond <= 0:
        return np.zeros(0, dtype=float)

    a = lattice_const
    r_wire = a / 10.0 if wire_radius is None else wire_radius   # m

    # bond-midpoint positions  x_mid(i) = (i + 0.5) a  (metres)
    x_mid = (np.arange(n_bond) + 0.5) * a                       # (N-1,)

    # kernel[i, j] = a / |x_i - x_j|  (i != j),  2 ln(a/r_wire)  (i == j)
    diff = x_mid[:, None] - x_mid[None, :]                      # (N-1, N-1) m
    absd = np.abs(diff)
    kernel = np.zeros_like(diff)
    off = ~np.eye(n_bond, dtype=bool)
    kernel[off] = a / absd[off]                                 # dimensionless * m? see below
    np.fill_diagonal(kernel, 2.0 * np.log(a / r_wire))          # dimensionless

    A_self = (MU_0 / (4.0 * np.pi)) * (kernel @ j_x)            # T*m
    return A_self


# ════════════════════════════════════════════════════════════════════
# FUNCTION 4 — Peierls phase from a vector potential
# ════════════════════════════════════════════════════════════════════
def compute_peierls_from_A(A_self: np.ndarray,
                           lattice_const: float,
                           ) -> np.ndarray:
    """
    Convert a per-bond vector potential into dimensionless Peierls phases.

        phi_self(i) = (e / hbar) * A_self(i) * a

    Parameters
    ----------
    A_self        : (N-1,) vector potential at bond midpoints (T*m)
    lattice_const : a, lattice constant in metres

    Returns
    -------
    phi_self : (N-1,) dimensionless Peierls phases.

    Validation
    ----------
    Checked by Validation 1 (uniform A field gives uniform phase equal to
    (e/hbar) * A_0 * a).
    """
    A_self = np.asarray(A_self, dtype=float)
    return (E_CHARGE / HBAR) * A_self * lattice_const          # dimensionless


