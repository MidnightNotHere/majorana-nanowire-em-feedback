# FUNCTION 1 — Peierls phase substitution on the BdG Hamiltonian
# ════════════════════════════════════════════════════════════════════
def apply_peierls_phases(H_BdG: np.ndarray,
                         N: int,
                         phi_ext: float,
                         phi_self: np.ndarray | None = None,
                         ) -> np.ndarray:
    """
    Apply Peierls phase substitution to a 4N x 4N Lutchyn-Oreg BdG
    Hamiltonian for a uniform external-flux phase plus an optional
    per-bond self-induced phase.

    Physics
    -------
    The Peierls substitution multiplies every nearest-neighbour hopping
    amplitude (kinetic AND Rashba spin-orbit) that transfers charge from
    site i to site i+1 by a complex phase:

        t_{i,i+1} -> t_{i,i+1} * exp(+i * phi_i)        (electron block)
        t_{i,i+1} -> t_{i,i+1} * exp(-i * phi_i)        (hole block)

    with  phi_i = phi_ext + phi_self[i].  The hole (lower-right 2N x 2N)
    block picks up the conjugate phase (tau_z structure), which is exactly
    what preserves particle-hole symmetry.  On-site terms (chemical
    potential, Zeeman) and the s-wave pairing block (which is on-site)
    are left untouched.

    Implementation builds a real antisymmetric phase matrix theta with
    theta[p, q] = -theta[q, p], so that H * exp(i*theta) is Hermitian by
    construction.  For a forward electron bond (site q = site p + 1, same
    Nambu sector) theta = +phi_i; for the hole sector theta = -phi_i.
    Because the kron(spin, site) ordering puts the Rashba cross-spin
    hopping at (site i -> site i+1) too, this single rule captures every
    bond automatically (verified by the PH-symmetry assertion).

    Parameters
    ----------
    H_BdG    : (4N, 4N) complex ndarray, Lutchyn-Oreg BdG Hamiltonian
    N        : number of lattice sites
    phi_ext  : uniform external-flux phase per bond (dimensionless)
               = pi * Phi_ext / Phi_0 / N
    phi_self : (N-1,) per-bond self-induced phase (dimensionless) or None

    Returns
    -------
    H_mod : (4N, 4N) complex ndarray with Peierls phases applied.

    Raises
    ------
    ValueError if particle-hole symmetry is broken (eps_PH > 1e-10) after
    the substitution.

    Validation
    ----------
    Checked by Validation 1 (uniform phase), Validation 3 (PH symmetry
    preserved for random phases & sizes) and Validation 4 (zero flux ->
    identity).
    """
    if H_BdG.shape != (4 * N, 4 * N):
        raise ValueError(
            f"H_BdG has shape {H_BdG.shape}, expected {(4*N, 4*N)} for N={N}."
        )

    # ── Per-bond total phase (dimensionless), length N-1 ──────────────
    phi_bond = np.full(N - 1, float(phi_ext))            # external flux
    if phi_self is not None:
        phi_self = np.asarray(phi_self, dtype=float)
        if phi_self.shape != (N - 1,):
            raise ValueError(
                f"phi_self has shape {phi_self.shape}, expected {(N-1,)}."
            )
        phi_bond = phi_bond + phi_self                   # add self term

    # ── Fast path: no phase at all -> return unchanged copy ───────────
    if not np.any(phi_bond):
        return H_BdG.copy()

    site, is_elec = _site_sector_maps(N)

    # forward bonds: same Nambu sector, site(q) == site(p) + 1
    same_sector = is_elec[:, None] == is_elec[None, :]      # (4N, 4N)
    forward     = same_sector & (site[None, :] == site[:, None] + 1)

    theta = np.zeros((4 * N, 4 * N), dtype=float)
    rows, cols = np.where(forward)
    bond_idx   = site[rows]                                  # = site(p) in 0..N-2
    sector_sgn = np.where(is_elec[rows], 1.0, -1.0)          # +1 elec, -1 hole
    theta[rows, cols] = sector_sgn * phi_bond[bond_idx]
    theta = theta - theta.T                                  # antisymmetrise

    H_mod = H_BdG * np.exp(1j * theta)                       # Hermitian-preserving

    # ── Never silently proceed with a symmetry-broken Hamiltonian ─────
    eps_ph = check_ph_symmetry_complex(H_mod, N)            # raises if > 1e-10
    if eps_ph > 1e-10:                                       # belt and braces
        raise ValueError(
            f"Peierls substitution broke PH symmetry: eps_PH = {eps_ph:.2e}."
        )
    return H_mod


