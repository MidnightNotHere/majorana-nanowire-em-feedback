_EULER_GAMMA = 0.5772156649015329


def figure1_peierls_validation(fname: str = "r4_figure1_peierls_validation.png"):
    """
    Validation 1: a uniform vector potential A_x = A_0 maps to a uniform
    Peierls phase phi = (e/hbar) A_0 a, and applying any phase preserves PH
    symmetry below 1e-10.
    """
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    N = 100
    a = LATTICE_A
    A0 = 1.0e-9                                   # T*m, uniform field
    A_uniform = np.full(N - 1, A0)               # (N-1,) T*m
    phi = compute_peierls_from_A(A_uniform, a)   # (N-1,) dimensionless
    A_recovered = phi / (E_CHARGE / HBAR * a)    # back out A from phase (T*m)
    x_mid = (np.arange(N - 1) + 0.5) * a * 1e9   # nm

    phi_ext_vals = np.linspace(0.0, np.pi, 10)
    eps_before, eps_after = [], []
    H = build_bdg_lo(N, mu=0.4, B_zeeman=0.8)
    for pe in phi_ext_vals:
        eps_before.append(check_ph_symmetry_complex(H, N))
        eps_after.append(check_ph_symmetry_complex(apply_peierls_phases(H, N, pe), N))

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(13, 5))
    ax1.plot(x_mid, A_recovered * 1e9, "b-", lw=3,
             label=r"recovered  $A=\phi\,\hbar/(e a)$")
    ax1.plot(x_mid, A_uniform * 1e9, "r--", lw=2, label=r"input  $A_0$")
    ax1.set_xlabel("bond midpoint position (nm)")
    ax1.set_ylabel(r"$A_x$ (nT$\cdot$m)")
    ax1.set_title("uniform $A$ field $\\to$ uniform Peierls phase")
    ax1.set_ylim(0, 2 * A0 * 1e9)
    ax1.legend()

    ax2.semilogy(phi_ext_vals, np.maximum(eps_before, 1e-18), "ko-",
                 label="before phases")
    ax2.semilogy(phi_ext_vals, np.maximum(eps_after, 1e-18), "bs-",
                 label="after phases")
    ax2.axhline(1e-10, color="r", ls="--", label=r"$10^{-10}$ tolerance")
    ax2.set_xlabel(r"$\phi_{\rm ext}$ (rad)")
    ax2.set_ylabel(r"PH error  $\varepsilon_{\rm PH}$")
    ax2.set_title("PH symmetry preserved under Peierls phases")
    ax2.legend()

    fig.suptitle("R4 Validation 1: Peierls Phase Implementation (uniform A field)",
                 fontsize=14, fontweight="bold")
    fig.tight_layout(rect=(0, 0, 1, 0.96))
    fig.savefig(fname, dpi=150)
    plt.close(fig)
    return fname


def figure2_biot_savart(fname: str = "r4_figure2_biot_savart.png"):
    """
    Validation 2: Biot-Savart self vector potential for a uniform current,
    compared with the finite-segment analytic continuum limit of the axial
    kernel,  A_center = (mu0/4pi) j0 [2 ln(L/2r) + 2 gamma].
    """
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    N = 100
    a = LATTICE_A
    j0 = 1.0                                       # A/m^2 uniform
    r_wire = a / 10.0
    A_self = biot_savart_self(np.full(N - 1, j0), N, a, r_wire)
    x_mid = (np.arange(N - 1) + 0.5) * a * 1e9     # nm
    L = N * a
    A_analytic = (MU_0 / (4 * np.pi)) * j0 * (2 * np.log(L / (2 * r_wire))
                                              + 2 * _EULER_GAMMA)
    rel_err = abs(A_self[N // 2] - A_analytic) / abs(A_analytic)

    L_fix = 1e-6
    r_fix = 20e-9
    Ns = np.array([25, 50, 100, 200, 400, 800])
    A_center_N = []
    for Nn in Ns:
        aa = L_fix / Nn
        A_center_N.append(biot_savart_self(np.full(Nn - 1, j0), Nn, aa, r_fix)[Nn // 2])
    A_inf = (MU_0 / (4 * np.pi)) * j0 * 2 * np.log(L_fix / r_fix)

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(13, 5))
    ax1.plot(x_mid, A_self * 1e6, "b-", lw=2.5, label="numerical")
    ax1.axhline(A_analytic * 1e6, color="r", ls="--", lw=2, label="analytic (center)")
    ax1.plot(x_mid[N // 2], A_self[N // 2] * 1e6, "ko", ms=8)
    ax1.set_xlabel("position along wire (nm)")
    ax1.set_ylabel(r"$A_{\rm self}$ ($\mu$T$\cdot$m)")
    ax1.set_title(f"uniform current, N=100\ncenter rel. error = {rel_err*100:.2f}%")
    ax1.legend()

    ax2.semilogx(Ns, np.array(A_center_N) * 1e6, "bo-", lw=2, ms=7,
                 label="numerical center")
    ax2.axhline(A_inf * 1e6, color="r", ls="--", lw=2,
                label=r"asymptotic $2\ln(L/r)$")
    ax2.set_xlabel("system size N (fixed $L$, $r_{\\rm wire}$)")
    ax2.set_ylabel(r"$A_{\rm self}$ at center ($\mu$T$\cdot$m)")
    ax2.set_title("convergence with system size")
    ax2.legend()

    fig.suptitle("R4 Validation 2: Biot-Savart Self-Term "
                 "(uniform current, analytic comparison)",
                 fontsize=14, fontweight="bold")
    fig.tight_layout(rect=(0, 0, 1, 0.96))
    fig.savefig(fname, dpi=150)
    plt.close(fig)
    return fname, rel_err


def figure3_current_density(fname: str = "r4_figure3_current_density.png"):
    """
    Current density along the wire for deep-topological, deep-trivial and
    near-boundary points.  A seed flux Phi = 0.1 Phi_0 is applied so the
    equilibrium current is non-zero (zero-flux current vanishes by symmetry).
    """
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from scipy.linalg import eigh

    N = 100
    a = LATTICE_A
    phi_ext = np.pi * 0.1 / N                      # Phi = 0.1 Phi_0
    x_mid = (np.arange(N - 1) + 0.5) * a * 1e9     # nm
    cases = [("deep topological\n$B=1.5\\Delta,\\ \\mu=0$", 0.0, 1.5, "b"),
             ("deep trivial\n$B=0.5\\Delta,\\ \\mu=0$",     0.0, 0.5, "r"),
             ("near boundary\n$B=\\Delta,\\ \\mu=0$",        0.0, 1.0, "g")]

    fig, axes = plt.subplots(1, 3, figsize=(16, 5))
    for ax, (label, mu, B, c) in zip(axes, cases):
        Hm = apply_peierls_phases(build_bdg_lo(N, mu=mu, B_zeeman=B), N, phi_ext)
        evals, evecs = eigh(Hm)
        j_x = compute_current_density(evecs, evals, N, T_HOP_SI,
                                      np.full(N - 1, phi_ext), a)
        ax.plot(x_mid, j_x, c + "-", lw=2)
        ax.axhline(0, color="k", lw=0.8)
        ax.set_xlabel("position along wire (nm)")
        ax.set_ylabel(r"$j_x$ (A/m$^2$)")
        ax.set_title(label)

    fig.suptitle("R4 Current Density from BdG Eigenstates "
                 "(InAs/Al, seed $\\Phi=0.1\\,\\Phi_0$)",
                 fontsize=14, fontweight="bold")
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    fig.savefig(fname, dpi=150)
    plt.close(fig)
    return fname


def figure4_phase_shift_preview(fname: str = "r4_figure4_phase_shift_preview.png",
                                N: int = 80):
    """
    Preview of the main result.  Left: Phi=0 phase diagram (blue
    topological / red trivial) with the analytic boundary.  Right: the same
    diagram with two numerically traced open-wire boundaries -- the
    gauge-invariant baseline (external flux only) and the inductive
    self-field boundary -- showing the inductive shift.
    """
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.colors import ListedColormap

    delta = 1.0
    mu_grid = np.linspace(-1.5, 1.5, 121)
    B_grid = np.linspace(0.0, 2.0, 121)
    MU, BB = np.meshgrid(mu_grid, B_grid)
    topo = (BB**2 > MU**2 + delta**2).astype(float)
    cmap = ListedColormap(["#c0392b", "#2471a3"])    # red trivial, blue topo
    ana = np.sqrt(mu_grid**2 + delta**2)

    phi_ext = np.pi * 0.1 / N                         # Phi = 0.1 Phi_0
    g0 = 0.03                                          # inductive feedback strength
    mu_b = np.linspace(-1.5, 1.5, 31)
    Bc_base, Bc_ind = [], []
    for m in mu_b:
        Bc_base.append(openwire_boundary_Bc(N, m, T_HOP_SI, LATTICE_A,
                                            phi_ext=phi_ext, g_feedback=0.0))
        Bc_ind.append(openwire_boundary_Bc(N, m, T_HOP_SI, LATTICE_A,
                                           phi_ext=phi_ext, g_feedback=g0))
    Bc_base = np.array(Bc_base)
    Bc_ind = np.array(Bc_ind)

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 6))
    for ax in (ax1, ax2):
        ax.pcolormesh(mu_grid, B_grid, topo, cmap=cmap, shading="auto",
                      vmin=0, vmax=1)
        ax.set_xlabel(r"chemical potential $\mu/\Delta$")
        ax.set_ylabel(r"Zeeman field $B_z/\Delta$")
    ax1.plot(mu_grid, ana, "w--", lw=2.5, label=r"$B=\sqrt{\mu^2+\Delta^2}$")
    ax1.set_title(r"$\Phi=0$  (topological = blue)")
    ax1.legend(loc="upper right")

    ax2.plot(mu_grid, ana, "w--", lw=2, label="analytic")
    ax2.plot(mu_b, Bc_base, "wo-", lw=2, ms=6,
             label=r"baseline ($\Phi_{\rm ext}$ only)")
    ax2.plot(mu_b, Bc_ind, "y^--", lw=2, ms=7, label="+ inductive self-field")
    ax2.set_title("inductive feedback shifts boundary ($g=%.2f$)" % g0)
    ax2.legend(loc="upper right", fontsize=11)

    fig.suptitle("R4 Figure 4: Topological Phase Boundary Shift Under "
                 "Inductive Feedback (preview)", fontsize=14, fontweight="bold")
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    fig.savefig(fname, dpi=150)
    plt.close(fig)

    shift_pct = 100.0 * (Bc_ind[0] - Bc_base[0]) / Bc_base[0]
    return fname, shift_pct


