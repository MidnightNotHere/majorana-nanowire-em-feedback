#
# Physics note on what shifts the boundary
# ----------------------------------------
# A spatially UNIFORM external flux is, at the bulk topological transition,
# gauge-equivalent to zero flux: the proper BdG ring (hole block = -h*)
# gives B_c = sqrt(mu^2 + Delta^2) EXACTLY, independent of Phi_ext (verified
# numerically to 0.0% shift).  The genuine boundary shift of the project's
# main result comes from the spatially NON-UNIFORM inductive self-field,
# which lifts translational invariance and is NOT gauge-removable (the
# s-wave pairing pins the gauge).  In R5 that self-field is found self-
# consistently; here we preview it one-shot, seeded by Phi_ext.
# ════════════════════════════════════════════════════════════════════
def build_ring_lo(N: int, mu: float, B: float, phi_ext: float = 0.0,
                  delta: float = 1.0,
                  t: float | None = None,
                  alpha_so: float | None = None) -> np.ndarray:
    """
    Real-space 4N x 4N Lutchyn-Oreg BdG Hamiltonian on a RING (periodic
    boundary), with a uniform Peierls flux phi_ext per bond on every bond
    (including the wrap bond N-1 -> 0).  Uses build_bdg_lo's conventions;
    the hole block is the proper -h* so PH symmetry holds exactly.

    A ring has no Majorana end modes, so min|E| is the clean bulk gap that
    closes exactly at the topological transition -- this is the noise-free
    boundary detector used for the Phi=0 phase diagram (Figure 4 left).
    """
    delta = float(delta)
    t = LO_PARAMS['t_norm'] * delta if t is None else t
    alpha = LO_PARAMS['alpha_norm'] * delta if alpha_so is None else alpha_so

    I2 = np.eye(2, dtype=complex)
    IN = np.eye(N, dtype=complex)
    sy = np.array([[0, -1j], [1j, 0]], dtype=complex)
    sz = np.array([[1, 0], [0, -1]], dtype=complex)
    isy = np.array([[0, 1], [-1, 0]], dtype=complex)            # i sigma_y

    # forward-hopping site matrix with Peierls phase, periodic
    T = np.zeros((N, N), dtype=complex)
    for i in range(N):
        T[i, (i + 1) % N] = np.exp(1j * phi_ext)               # bond i -> i+1

    h_kin = (2.0 * t - mu) * np.kron(I2, IN) - t * np.kron(I2, T + T.conj().T)
    h_Z   = B * np.kron(sz, IN)
    h_SO  = (1j * alpha / 2.0) * np.kron(sy, T - T.conj().T)
    h     = h_kin + h_Z + h_SO

    Dblk = delta * np.kron(isy, IN)
    H = np.block([[h, Dblk], [Dblk.conj().T, -h.conj()]])      # proper -h* hole block
    return H


def ring_min_gap(N: int, mu: float, B: float, phi_ext: float = 0.0,
                 delta: float = 1.0) -> float:
    """Clean bulk gap (min|E|) of the LO ring -- closes at the boundary."""
    H = build_ring_lo(N, mu, B, phi_ext, delta)
    return float(np.min(np.abs(np.linalg.eigvalsh(H))))


def ring_boundary_Bc(N: int, mu: float, phi_ext: float = 0.0,
                     delta: float = 1.0, half: float = 0.25,
                     n_grid: int = 251) -> float:
    """
    Critical Zeeman field B_c(mu) on the ring: B that minimises the clean
    bulk gap (global argmin over a fine B grid centred on the analytic
    boundary).  At phi_ext = 0 this returns sqrt(mu^2 + delta^2) to grid
    resolution.
    """
    ana = np.sqrt(mu**2 + delta**2)
    Bg = np.linspace(max(0.02, ana - half), ana + half, n_grid)
    gaps = np.array([ring_min_gap(N, mu, B, phi_ext, delta) for B in Bg])
    return float(Bg[int(np.argmin(gaps))])


def openwire_boundary_Bc(N: int, mu: float,
                         t_hop_si: float, lattice_const: float,
                         phi_ext: float = 0.0, g_feedback: float = 0.0,
                         delta: float = 1.0, threshold: float = 0.25,
                         half: float = 0.45, n_grid: int = 181,
                         wire_radius: float | None = None) -> float:
    """
    Critical Zeeman field B_c(mu) on the OPEN wire, optionally including the
    one-shot inductive self-field (seeded by phi_ext, scaled by the
    dimensionless feedback strength g_feedback -- the stand-in for the R5
    circuit inductance).

    Detector: first B (scanning upward) at which the lowest excitation
    |E|_min drops below `threshold`, i.e. a Majorana zero-mode pair appears.
    The absolute value carries a finite-size offset from sqrt(mu^2+delta^2),
    but that offset cancels in the *relative* shift between g_feedback = 0
    (gauge-invariant baseline) and g_feedback > 0 (inductive feedback),
    which is the physically meaningful quantity reported in Validation 6.
    """
    from scipy.linalg import eigh, eigvalsh   # local import; heavy module
    a = lattice_const
    ana = np.sqrt(mu**2 + delta**2)
    Bg = np.linspace(max(0.05, ana - half), ana + half, n_grid)
    for B in Bg:
        with contextlib.redirect_stdout(io.StringIO()):
            H = build_bdg_lo(N, mu=mu, B_zeeman=B, delta=delta)
        if phi_ext or g_feedback:
            # seed a current with the external flux, then add g * self-field
            evals, evecs = eigh(apply_peierls_phases(H, N, phi_ext))
            j_x = compute_current_density(evecs, evals, N, t_hop_si,
                                          np.full(N - 1, phi_ext), a)
            A_self = biot_savart_self(j_x, N, a, wire_radius)
            phi_self = g_feedback * compute_peierls_from_A(A_self, a)
            H = apply_peierls_phases(H, N, phi_ext, phi_self)
        if np.min(np.abs(eigvalsh(H))) < threshold:
            return float(B)
    return float(Bg[-1])


