# CLASS — PeierlsEMLayer: the full EM coupling, R5-ready
# ════════════════════════════════════════════════════════════════════
class PeierlsEMLayer:
    """
    Stateful wrapper around the R4 EM coupling, exposing the exact
    interface that R5's self-consistent fixed-point loop calls on every
    iteration.

    Typical R5 usage (one iteration)
    --------------------------------
        layer = PeierlsEMLayer(N, t_hop=T_HOP_SI, lattice_const=LATTICE_A)
        # solve eigenproblem for current H -> (evals, evecs)
        H_new, phi_total = layer.apply(H0, phi_ext, evecs, evals)
        # check convergence on A_self / phi_self, Anderson-mix, repeat
    """

    def __init__(self, N: int, t_hop: float, lattice_const: float,
                 wire_radius: float | None = None):
        self.N = int(N)
        self.t_hop = float(t_hop)                  # J
        self.a = float(lattice_const)              # m
        self.wire_radius = (lattice_const / 10.0
                            if wire_radius is None else float(wire_radius))  # m

    # ── current density from eigenstates (SI) ─────────────────────────
    def current_density(self, eigenvectors: np.ndarray,
                        eigenvalues: np.ndarray,
                        phi_total: np.ndarray) -> np.ndarray:
        """j_x (A/m^2) at bond midpoints; thin wrapper over the free fn."""
        return compute_current_density(eigenvectors, eigenvalues, self.N,
                                       self.t_hop, phi_total, self.a)

    # ── self vector potential from current (SI) ───────────────────────
    def vector_potential(self, j_x: np.ndarray) -> np.ndarray:
        """A_self (T*m) at bond midpoints from j_x via Biot-Savart."""
        return biot_savart_self(j_x, self.N, self.a, self.wire_radius)

    # ── full apply: external flux (+ optional self-consistent A) ──────
    def apply(self, H_BdG: np.ndarray,
              phi_ext: float,
              eigenvectors: np.ndarray | None = None,
              eigenvalues: np.ndarray | None = None,
              ) -> tuple[np.ndarray, np.ndarray]:
        """
        Apply Peierls phases to H_BdG.

        If eigenvectors / eigenvalues are None -> external flux only.
        If provided -> also compute the self-consistent A_self from the
        current density and fold its Peierls phase into the Hamiltonian.

        Returns
        -------
        (H_modified, phi_total) where phi_total is the (N-1,) per-bond
        total phase actually applied (phi_ext + phi_self).
        """
        if eigenvectors is None or eigenvalues is None:
            phi_self = None
            phi_total = np.full(self.N - 1, float(phi_ext))
        else:
            # current is evaluated at the phase the eigenstates were found
            phi_eval = np.full(self.N - 1, float(phi_ext))
            j_x      = self.current_density(eigenvectors, eigenvalues, phi_eval)
            A_self   = self.vector_potential(j_x)
            phi_self = compute_peierls_from_A(A_self, self.a)
            phi_total = float(phi_ext) + phi_self

        H_mod = apply_peierls_phases(H_BdG, self.N, phi_ext, phi_self)
        return H_mod, phi_total


